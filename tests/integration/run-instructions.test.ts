import assert from "node:assert/strict";
import { test } from "node:test";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { createRunInstructions, enqueueRunInstruction } from "../../src/runtime/run-instructions.ts";
import { createRunState, saveRunState } from "../../src/runtime/run-state.ts";
import { createTaskGraph, taskNode } from "../../src/planning/schemas.ts";
import { createSakuraAgent } from "../../src/runtime/create-agent.ts";
import { piFixture } from "../helpers/pi-fixture.ts";

test("business instructions target a live native Pi session and pending plan changes wait for a boundary",async(t)=>{
  let started!:()=>void, release!:()=>void;
  const ready=new Promise<void>(resolve=>started=resolve), barrier=new Promise<void>(resolve=>release=resolve);
  const fixture=await piFixture(async(_context,_options,call)=>{if(call===1){started();await barrier;}return {content:[{type:"text",text:`turn ${call}`}]};});
  t.after(fixture.cleanup);
  const runId="run-instruction",dir=join(fixture.directory,".sakura","runs",runId);
  const graph=createTaskGraph({id:"plan-instructions",rootTask:"review",nodes:[taskNode({id:"reader",title:"read",description:"initial",role:"explorer",dependencies:[],priority:1}),taskNode({id:"next",title:"next",description:"pending",role:"reviewer",dependencies:["reader"],priority:1})]});
  graph.nodes.reader.status="running";
  const state=createRunState({runId,graph});state.phase="running";await saveRunState(dir,state);
  const agent=await createSakuraAgent({role:"explorer",cwd:fixture.directory,...fixture.config});t.after(()=>agent.dispose());
  const events:unknown[]=[];const control=createRunInstructions(dir,event=>events.push(event));t.after(()=>control.close());
  const detach=control.attach("reader",agent.session);
  const work=agent.session.prompt("initial");await ready;
  const steer=await enqueueRunInstruction(fixture.directory,runId,{target:"reader",mode:"steer",text:"LIVE_STEER"});
  const follow=await enqueueRunInstruction(fixture.directory,runId,{target:"reader",mode:"follow-up",text:"LIVE_FOLLOW"});
  const plan=await enqueueRunInstruction(fixture.directory,runId,{target:"next",mode:"plan",text:"PLAN_MARKER"});
  await assert.rejects(enqueueRunInstruction(fixture.directory,runId,{target:"reader",mode:"plan",text:"unsafe"}),/pending/);
  assert.equal(graph.version,1);assert.equal(graph.nodes.next.description,"pending");
  await control.boundary(graph);
  assert.equal(graph.version,2);assert.match(graph.nodes.next.description,/PLAN_MARKER/);
  release();await work;detach();
  assert.equal(fixture.requests.length,3);
  assert.match(JSON.stringify(fixture.requests[1]),/LIVE_STEER/);assert.match(JSON.stringify(fixture.requests[2]),/LIVE_FOLLOW/);
  for(const instruction of [steer,follow]) assert.equal(JSON.parse(await readFile(join(dir,"instructions",`${instruction.id}.json`),"utf8")).status,"dispatched");
  assert.equal(JSON.parse(await readFile(join(dir,"instructions",`${plan.id}.json`),"utf8")).graphVersion,2);
  const stale=await enqueueRunInstruction(fixture.directory,runId,{target:"reader",mode:"steer",text:"do not send after cancellation"});
  await control.close("Run cancelled");
  assert.equal(JSON.parse(await readFile(join(dir,"instructions",`${stale.id}.json`),"utf8")).status,"rejected");
  assert.equal(fixture.requests.length,3);assert.equal(events.length,4);
});
